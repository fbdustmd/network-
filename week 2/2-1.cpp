#include <iostream>

int main()
{
    int value = 10;

    auto callback = [value]() { // 람다 표현식
        std::cout << value << std::endl;
    };

    //람다 표현식의 기본 작동 원리는 [캡처](매개변수) -> 반환형 {실행할 코드};
    //이런식으로 구성이 되어있음. 여기서 캡처는 람다함수가 선언되는 순간에 이미 지정이 되어있는 값을
    //복사하는 느낌임 그래서 람다함수를 선언한 후에 이 코드로 예시를 들면 value 값을 람다함수 선언후 변경을 할시 
    // 값은 그대로 10임. vlaue = 10 이라는걸 이미 캡처를 해놨기 때문. 주소값을 넣어놓으면 포인터처럼 계속 따라가긴함 

    callback();

    return 0;
}